export const t = derived(locale, ($locale) => (key: string, params?: Record<string, string | number>) => {
  const table = $locale === 'en' ? en : ru;
  let text = table[key] ?? ru[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
});

export function pluralKey(lang: Locale, n: number, base: string): string {
  if (lang === 'en') return `${base}.${n === 1 ? 'one' : 'many'}`;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${base}.one`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${base}.few`;
  return `${base}.many`;
}

export function applyLocale(next: Locale) {
  locale.set(next);
  try {
    const raw = localStorage.getItem('gameLauncherSettings');
    const data = raw ? JSON.parse(raw) : {};
    data.language = next;
    localStorage.setItem('gameLauncherSettings', JSON.stringify(data));
  } catch (e) {
    console.error('Не удалось сохранить язык', e);
  }
}

export function initLocale() {
  try {
    const raw = localStorage.getItem('gameLauncherSettings');
    const lang = raw ? JSON.parse(raw).language : 'ru';
    locale.set(lang === 'en' ? 'en' : 'ru');
  } catch {
    locale.set('ru');
  }
}
